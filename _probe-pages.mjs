import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { parseBboxXml } from './engine/lib/annotate.mjs';
const pexec = promisify(execFile);
const TASK = process.argv[2];
const taskDir = path.join('web/data/tasks', TASK);
const src = fs.readdirSync(taskDir).find(f => /\.docx$/i.test(f) && !/extracted/i.test(f) && !/^~\$/.test(f));
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'probe-'));
await pexec('C:\\Program Files\\LibreOffice\\program\\soffice.exe', ['--headless','--convert-to','pdf','--outdir',work, path.join(taskDir, src)], { timeout: 900000, windowsHide: true });
const pdf = path.join(work, src.replace(/\.[^.]+$/, '.pdf'));
const { stdout } = await pexec('pdftotext', ['-bbox', pdf, '-'], { encoding: 'utf8', maxBuffer: 1024*1024*1024 });
const pages = parseBboxXml(stdout);
const land = pages.map((p,i)=>({i:i+1,w:Math.round(p.w),h:Math.round(p.h)})).filter(p=>p.w>p.h);
console.log('总页数', pages.length, '横版页数', land.length);
console.log(land.slice(0,20).map(p=>`p${p.i}(${p.w}x${p.h})`).join(' '));
fs.rmSync(work,{recursive:true,force:true});
